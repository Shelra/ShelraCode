import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const modelPath = resolve(root, "schema", "model.json");
const outputPath = resolve(root, "src", "generated", "schema.ts");

const raw = readFileSync(modelPath, "utf8");
const model = JSON.parse(raw) as Record<string, Record<string, string>>;
const user = model.User;
if (!user) throw new Error("schema/model.json must define a User type");

const fields = Object.keys(user);
const hash = createHash("sha256").update(raw).digest("hex");
const lines = [
  "// GENERATED by scripts/build-schema.ts from schema/model.json — do not edit by hand.",
  `export const SCHEMA_HASH = "${hash}";`,
  `export const USER_FIELDS = [${fields.map((field) => JSON.stringify(field)).join(", ")}] as const;`,
  "export type UserField = (typeof USER_FIELDS)[number];",
  "export interface User {",
  ...fields.map((field) => `  ${field}: ${user[field] === "number" ? "number" : "string"};`),
  "}",
  "",
];
mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, lines.join("\n"), "utf8");
console.log(`wrote ${outputPath} (${fields.length} fields)`);
